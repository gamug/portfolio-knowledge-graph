"""Build the FIBO glossary slice from the pinned release (T-211, brief §4.2).

The slice is reference data, not an import: it describes 25 FIBO seeds and the ancestors the
release itself describes, keeps only labels, definitions, named parents and the Commons annotation
notes, and drops ``rdf:type`` so no FIBO term becomes an ``owl:Class`` in this repository
(NR-004). The reviewed Spanish labels and definitions come from ``schema/fibo_terms.csv`` and are
the thesis authors' translation, not FIBO's text.

The release is never committed. ``cli/build_fibo_slice.py`` checks its sha256 first and rebuilds
``schema/fibo.ttl`` deterministically; the committed slice is what the hermetic tests read.
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

from rdflib import Namespace
from rdflib.namespace import DCTERMS, OWL, RDFS
from rdflib.term import Literal, Node, URIRef

from projection.fibo_terms import (
    FIBO_BASE,
    OUR_NAMESPACE,
    PINNED_SHA256,
    FiboTermsError,
    Term,
    iter_release_modules,
    read_terms,
    sha256,
)

CMNS_AV = Namespace("https://www.omg.org/spec/Commons/AnnotationVocabulary/")
SKOS = Namespace("http://www.w3.org/2004/02/skos/core#")
RELEASE_VERSION = "FIBO 2026Q2"
RELEASE_SUBJECT = URIRef(FIBO_BASE + "AboutFIBOProd/")
HEADER_IRI = URIRef(OUR_NAMESPACE + "FiboReferenceSlice")
HEADER_SHA = URIRef(OUR_NAMESPACE + "fiboReleaseSha256")

#: The predicates the slice keeps from the release, in the order the file writes them.
KEPT_PREDICATES: tuple[URIRef, ...] = (
    RDFS.label,
    SKOS.definition,
    RDFS.subClassOf,
    CMNS_AV.explanatoryNote,
    CMNS_AV.usageNote,
    CMNS_AV.synonym,
    CMNS_AV.abbreviation,
    CMNS_AV.example,
)

HEADER_COMMENT = (
    "FIBO 2026Q2 glossary slice: the 25 reviewed seeds and the ancestors the release describes. "
    "FIBO's own text is the untagged or @en literal; every @es literal is the thesis authors' "
    "translation, never FIBO's words. Generated by cli/build_fibo_slice.py; do not edit."
)


@dataclass(frozen=True)
class SliceResult:
    """The triples to write and the counts the brief §4.2 pins."""

    entries: tuple[str, ...]
    triples: tuple[tuple[Node, Node, Node], ...]
    english_counts: Mapping[str, int]
    spanish_statements: int
    header_statements: int

    @property
    def english_statements(self) -> int:
        return sum(self.english_counts.values())

    @property
    def total_statements(self) -> int:
        return self.english_statements + self.spanish_statements + self.header_statements


def _is_fibo(iri: Node) -> bool:
    return isinstance(iri, URIRef) and str(iri).startswith(FIBO_BASE)


def _release_facts(
    zip_path: str | Path,
) -> tuple[set[URIRef], dict[URIRef, set[URIRef]], str]:
    """The release's described subjects, named ``rdfs:subClassOf`` edges and licence text.

    One module is held at a time; the whole release is never materialised. The licence is the
    ``dct:license`` of ``AboutFIBOProd`` and is copied verbatim into the slice header.
    """
    described: set[URIRef] = set()
    parents: dict[URIRef, set[URIRef]] = defaultdict(set)
    licence: str | None = None
    for _name, graph in iter_release_modules(zip_path):
        described.update(subject for subject in graph.subjects() if isinstance(subject, URIRef))
        for subject, obj in graph.subject_objects(RDFS.subClassOf):
            if isinstance(subject, URIRef) and isinstance(obj, URIRef):
                parents[subject].add(obj)
        value = graph.value(RELEASE_SUBJECT, DCTERMS.license)
        if isinstance(value, Literal):
            licence = str(value)
    if licence is None:
        raise FiboTermsError(f"{zip_path}: AboutFIBOProd carries no dct:license")
    return described, parents, licence


def _closure(
    seeds: Iterable[URIRef],
    described: set[URIRef],
    parents: Mapping[URIRef, set[URIRef]],
) -> set[URIRef]:
    """The seeds plus every ancestor the release describes through a named ``fibo:`` edge.

    A parent outside the release stays the object of its edge but is not expanded, so OMG Commons
    terms never become entries and never need a label or definition.
    """
    entries = set(seeds)
    frontier = list(seeds)
    while frontier:
        subject = frontier.pop()
        for parent in sorted(parents.get(subject, ()), key=str):
            if _is_fibo(parent) and parent in described and parent not in entries:
                entries.add(parent)
                frontier.append(parent)
    return entries


def _kept_triples(zip_path: str | Path, entries: set[URIRef]) -> set[tuple[Node, Node, Node]]:
    kept: set[tuple[Node, Node, Node]] = set()
    for _name, graph in iter_release_modules(zip_path):
        for subject, predicate, obj in graph:
            if subject not in entries or predicate not in KEPT_PREDICATES:
                continue
            if predicate == RDFS.subClassOf and not isinstance(obj, URIRef):
                continue
            kept.add((subject, predicate, obj))
    return kept


def _spanish_layer(triples: set[tuple[Node, Node, Node]], terms: Sequence[Term]) -> int:
    """Add ``rdfs:label``@es and ``skos:definition``@es for every reviewed seed.

    A row is reviewed only when both Spanish columns are filled; a half-filled row is not loaded.
    """
    added = 0
    for term in terms:
        if not (term.label_es and term.definition_es):
            continue
        iri = URIRef(term.fibo_iri)
        triples.add((iri, RDFS.label, Literal(term.label_es, lang="es")))
        triples.add((iri, SKOS.definition, Literal(term.definition_es, lang="es")))
        added += 2
    return added


def build_result(
    zip_path: str | Path,
    terms_path: str | Path,
    *,
    expected_sha256: str = PINNED_SHA256,
) -> SliceResult:
    """Check the pin, read the terms and assemble the slice triples.

    ``expected_sha256`` is a parameter so the hermetic tests can accept a synthetic zip; the CLI
    always passes the pinned value.
    """
    path = Path(zip_path)
    if not path.is_file():
        raise FiboTermsError(f"{path}: not a file")
    actual = sha256(path)
    if actual != expected_sha256:
        raise FiboTermsError(
            f"{path}: sha256 {actual} is not the pinned {expected_sha256}; refusing the release"
        )
    terms = read_terms(terms_path)
    seeds = {URIRef(term.fibo_iri) for term in terms}
    described, parents, licence = _release_facts(path)
    entries = _closure(seeds, described, parents)
    missing = sorted(str(seed) for seed in seeds if seed not in entries)
    if missing:
        raise FiboTermsError(f"{path}: seeds missing from the release: {', '.join(missing)}")

    triples = _kept_triples(path, entries)
    english_counts = {
        str(predicate): sum(1 for subject, p, _ in triples if subject in entries and p == predicate)
        for predicate in KEPT_PREDICATES
    }
    spanish = _spanish_layer(triples, terms)
    header = {
        (HEADER_IRI, OWL.versionInfo, Literal(RELEASE_VERSION)),
        (HEADER_IRI, HEADER_SHA, Literal(PINNED_SHA256)),
        (HEADER_IRI, DCTERMS.license, Literal(licence)),
        (HEADER_IRI, RDFS.comment, Literal(HEADER_COMMENT)),
    }
    triples |= header
    return SliceResult(
        entries=tuple(sorted(str(entry) for entry in entries)),
        triples=tuple(
            sorted(triples, key=lambda triple: tuple(_sort_key(term) for term in triple))
        ),
        english_counts=english_counts,
        spanish_statements=spanish,
        header_statements=len(header),
    )


def _sort_key(term: Node) -> tuple[str, str, str]:
    if isinstance(term, Literal):
        return ("literal", term.language or "", str(term))
    return (type(term).__name__, "", str(term))


_PREFIXES = (
    ("", OUR_NAMESPACE),
    ("cmns-av", str(CMNS_AV)),
    ("dcterms", str(DCTERMS)),
    ("owl", str(OWL)),
    ("rdfs", str(RDFS)),
    ("skos", str(SKOS)),
)

_PREDICATE_NAMES = {
    RDFS.label: "rdfs:label",
    SKOS.definition: "skos:definition",
    RDFS.subClassOf: "rdfs:subClassOf",
    CMNS_AV.explanatoryNote: "cmns-av:explanatoryNote",
    CMNS_AV.usageNote: "cmns-av:usageNote",
    CMNS_AV.synonym: "cmns-av:synonym",
    CMNS_AV.abbreviation: "cmns-av:abbreviation",
    CMNS_AV.example: "cmns-av:example",
    OWL.versionInfo: "owl:versionInfo",
    DCTERMS.license: "dcterms:license",
    HEADER_SHA: ":fiboReleaseSha256",
    RDFS.comment: "rdfs:comment",
}


def _render(term: Node) -> str:
    if isinstance(term, Literal):
        return term.n3()
    if isinstance(term, URIRef):
        if str(term) == str(HEADER_IRI):
            return ":FiboReferenceSlice"
        return f"<{term}>"
    raise FiboTermsError(f"cannot serialise blank node {term!r}; the slice keeps named terms only")


def serialize(result: SliceResult) -> str:
    """Write a deterministic, sorted Turtle document (same inputs -> same bytes)."""
    lines = [
        "# FIBO 2026Q2 glossary slice. Generated by cli/build_fibo_slice.py; do not edit.",
        "# FIBO's own text is untagged or @en; every @es literal is the thesis authors' translation.",
        "",
    ]
    lines.extend(
        f"@prefix {prefix}: <{iri}> ." if prefix else f"@prefix : <{iri}> ."
        for prefix, iri in _PREFIXES
    )
    lines.append("")
    grouped: dict[Node, dict[Node, list[Node]]] = defaultdict(lambda: defaultdict(list))
    for subject, predicate, obj in result.triples:
        grouped[subject][predicate].append(obj)

    subjects = sorted(grouped, key=_sort_key)
    if HEADER_IRI in grouped:
        subjects.remove(HEADER_IRI)
        subjects.insert(0, HEADER_IRI)
    for subject in subjects:
        predicates = grouped[subject]
        parts: list[str] = []
        for predicate in (
            *KEPT_PREDICATES,
            OWL.versionInfo,
            HEADER_SHA,
            DCTERMS.license,
            RDFS.comment,
        ):
            if predicate not in predicates:
                continue
            objects = sorted(predicates[predicate], key=_sort_key)
            for obj in objects:
                parts.append(f"    {_PREDICATE_NAMES[predicate]} {_render(obj)}")
        if parts:
            lines.append(_render(subject))
            lines.append(" ;\n".join(parts) + " .")
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def build_slice(
    zip_path: str | Path,
    terms_path: str | Path,
    out_path: str | Path,
    *,
    expected_sha256: str = PINNED_SHA256,
) -> SliceResult:
    """Build and write the slice; returns the counts so the caller can print them."""
    result = build_result(zip_path, terms_path, expected_sha256=expected_sha256)
    Path(out_path).write_bytes(serialize(result).encode("utf-8"))
    return result


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--zip", required=True, type=Path, metavar="PATH", help="prod.ttl.zip")
    parser.add_argument(
        "--terms",
        type=Path,
        default=Path("schema/fibo_terms.csv"),
        metavar="PATH",
        help="the 25-row terms file (default: schema/fibo_terms.csv)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("schema/fibo.ttl"),
        metavar="PATH",
        help="output Turtle file (default: schema/fibo.ttl)",
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    """0 when the slice is written, 1 on a check failure, 2 on a bad argument."""
    args = parse_args(argv)
    if not args.zip.is_file():
        print(f"bad argument: --zip {args.zip} is not a file", file=sys.stderr)
        return 2
    if not args.terms.is_file():
        print(f"bad argument: --terms {args.terms} is not a file", file=sys.stderr)
        return 2
    try:
        result = build_slice(args.zip, args.terms, args.out)
    except FiboTermsError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    print(f"wrote {args.out}: {len(result.entries)} entries, {result.total_statements} statements")
    for predicate, count in result.english_counts.items():
        print(f"  {predicate.rsplit('/', 1)[-1]}: {count}")
    print(f"  @es statements: {result.spanish_statements}")
    print(f"  header statements: {result.header_statements}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
