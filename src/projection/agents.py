def graph_name(label: str, window: str, slug: str) -> str:
    if not re.fullmatch(RUN_LABEL_PATTERN, label):
        raise AgentsError(f"run label {label!r} does not match {RUN_LABEL_PATTERN}")
    if window not in WINDOWS:
        raise AgentsError(f"unknown window {window!r}")
    if slug not in SLUGS:
        raise AgentsError(f"unknown block-F slug {slug!r}")
    return f"{GRAPH_PREFIX}{label}:{window}:{slug}"


