def _news(path: Path) -> NewsData:  # noqa: C901 -- one source contract read in one place
    raw = _load_json(path)
    actions = tuple(
        _news_action(item, f"{path}.actions[{index}]")
        for index, item in enumerate(_object_list(raw.get("actions"), f"{path}.actions"))
    )
    dates = tuple(
        _news_date(item, f"{path}.dates[{index}]")
        for index, item in enumerate(_object_list(raw.get("dates"), f"{path}.dates"))
    )
    levels = tuple(
        _news_level(item, f"{path}.levels_v2.decisions[{index}]")
        for index, item in enumerate(
            _object_list(
                _mapping(raw.get("levels_v2"), f"{path}.levels_v2").get("decisions"),
                f"{path}.levels_v2.decisions",
            )
        )
    )
    fills = tuple(
        _news_fill(item, f"{path}.fills[{index}]")
        for index, item in enumerate(_object_list(raw.get("fills"), f"{path}.fills"))
    )
    tickers_raw = _mapping(raw.get("canonical_tickers"), f"{path}.canonical_tickers")
    tickers: dict[int, str] = {}
    for ticker, asset in tickers_raw.items():
        _text(ticker, f"{path}.canonical_tickers key")
        number = _positive_int(asset, f"{path}.canonical_tickers.{ticker}")
        if number in tickers:
            raise AgentsError(f"{path}: canonical_tickers repeats engine id {number}")
        tickers[number] = ticker
    level = _mapping(raw.get("levels_v2"), f"{path}.levels_v2")
    _non_negative_int(level.get("b_news_exits"), f"{path}.levels_v2.b_news_exits")
    _list(level.get("sessions"), f"{path}.levels_v2.sessions")
    _text(raw.get("news_mode"), f"{path}.news_mode")
    _decimal(raw.get("news_alpha"), f"{path}.news_alpha")
    _sha(raw.get("news_table_sha256"), f"{path}.news_table_sha256")
    _int(raw.get("run_id"), f"{path}.run_id")
    keys = [
        (str(item["decision_date"]), int(item["asset_id"]), str(item["action"])) for item in actions
    ]
    if len(keys) != len(set(keys)):
        raise AgentsError(f"{path}: duplicate (decision_date, asset_id, action) key")
    evidence_keys = [(key[0], key[1]) for key in keys]
    if len(evidence_keys) != len(set(evidence_keys)):
        raise AgentsError(f"{path}: two actions share one (decision_date, asset_id) evidence IRI")
    date_keys = [str(item["decision_date"]) for item in dates]
    if len(date_keys) != len(set(date_keys)):
        raise AgentsError(f"{path}: duplicate decision_date in dates")
    level_keys = [str(item["date"]) for item in levels]
    if len(level_keys) != len(set(level_keys)):
        raise AgentsError(f"{path}: duplicate date in levels_v2.decisions")
    if set(date_keys) != set(level_keys):
        raise AgentsError(f"{path}: dates and levels_v2.decisions name different dates")
    top_by_date = Counter(str(item["decision_date"]) for item in actions)
    for date in dates:
        raw_actions = _list(date["actions"], f"{path}.dates.actions")
        if len(raw_actions) != top_by_date[str(date["decision_date"])]:
            raise AgentsError(
                f"{path}: date {date['decision_date']} lists {len(raw_actions)} actions, "
                f"the top-level actions have {top_by_date[str(date['decision_date'])]}"
            )
    action_by_key = {key: item for key, item in zip(keys, actions, strict=True)}
    for fill in fills:
        key = (str(fill["decision_date"]), int(fill["replaces"]), "veto")
        action = action_by_key.get(key)
        if action is None:
            raise AgentsError(f"{path}: fill {fill!r} matches no veto action")
        if action.get("replaced_by") != fill["asset_id"]:
            raise AgentsError(
                f"{path}: fill {fill['decision_date']}/{fill['replaces']} buys "
                f"{fill['asset_id']}, the action says {action.get('replaced_by')!r}"
            )
    return NewsData(raw, actions, dates, levels, fills, tickers)


