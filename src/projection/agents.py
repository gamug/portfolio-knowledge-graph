def _counts(
    data: NewsData,
    manager: Sequence[ManagerCall],
    narrator: Sequence[NarratorText],
    bull: BullData,
    sector: int,
) -> Counts:
    actions = Counter(str(item["action"]) for item in data.actions)
    return Counts(
        manager_calls=len(manager),
        manager_fallbacks=sum(1 for item in manager if item.raw["fallback"]["used_rule"] is True),
        manager_repairs=sum(1 for item in manager if item.raw["repair_used"] is True),
        narrator_texts=len(narrator),
        news_pool_actions={
            "veto": actions.get("veto", 0),
            "promotion": actions.get("promotion", 0),
        },
        news_date_records=len(data.dates),
        news_level_c_decisions=sum(
            1 for item in data.levels if bool(item["c_flags"]) or bool(item["c_flagged"])
        ),
        news_level_d_decisions=sum(1 for item in data.levels if item["d_fired"] is True),
        news_exits=int(data.raw["levels_v2"]["b_news_exits"]),
        news_sector_rejections=sector,
        bull_triggered=sum(1 for item in bull.decisions if item["triggered"] is True),
    )


def _news_item_index(
    root: Path, manifest: Mapping[str, Any], sums: Mapping[str, str]
) -> dict[tuple[str, str], news_rows.NewsRow]:
    """Parse block D's news rows and index them by (item_id, ticker).

    The manifest's ``news_rows_file`` is the only source; its hash is checked against both the
    manifest and ``SHA256SUMS`` before D's parser reads it. A key that maps to two item kinds is
    refused, never guessed.
    """
    block = manifest.get("news_rows_file")
    if block is None:
        return {}
    record = _mapping(block, "manifest.news_rows_file")
    relative = _text(record.get("file"), "manifest.news_rows_file.file")
    digest = _sha(record.get("sha256"), "manifest.news_rows_file.sha256")
    assert digest is not None
    _verify_file(root, relative, digest, sums)
    columns = record.get("columns")
    if not isinstance(columns, list) or not columns:
        raise AgentsError("manifest.news_rows_file.columns must be a non-empty list")
    contract = NewsRowsContract(
        path=root / relative,
        sha256=digest,
        rows=_positive_int(record.get("rows"), "manifest.news_rows_file.rows"),
        model_revision=_text(
            record.get("model_revision"), "manifest.news_rows_file.model_revision"
        ),
        columns=tuple(str(column) for column in columns),
        readme=None,
    )
    try:
        rows = news_rows.parse_rows(contract)
    except news_rows.NewsError as exc:
        raise AgentsError(str(exc)) from exc
    index: dict[tuple[str, str], news_rows.NewsRow] = {}
    kinds: dict[tuple[str, str], str] = {}
    for row in rows:
        key = (row.item_id, row.ticker)
        prior = kinds.setdefault(key, row.item_kind)
        if prior != row.item_kind:
            raise AgentsError(
                f"{contract.path}: ({key[0]}, {key[1]}) maps to both {prior!r} and "
                f"{row.item_kind!r}; the :NewsItem IRI is ambiguous"
            )
        index[key] = row
    return index


def _window(  # noqa: C901, PLR0912 -- one source contract read in one place
    root: Path,
    window: str,
    run: Mapping[str, Any],
    sums: Mapping[str, str],
    news_items: Mapping[tuple[str, str], news_rows.NewsRow],
) -> WindowData:
    paths: dict[str, Path] = {}
    hashes: dict[str, str] = {}
    declared = _mapping(run.get("files_sha256"), f"manifest.{window}.files_sha256")
    for key in ("manager_calls", "narrator", "news_actions", "bull_mode", "jsonl"):
        relative = _text(run.get(f"{key}_file"), f"manifest.{window}.{key}_file")
        if key not in declared:
            raise AgentsManifestError(f"manifest.{window}.files_sha256: no {key} hash")
        hashes[key] = _verify_file(root, relative, str(declared[key]), sums)
        paths[key] = root / relative
    manager = _manager_calls(paths["manager_calls"])
    narrator = _narrator_texts(paths["narrator"])
    news = _news(paths["news_actions"])
    used_items: dict[tuple[str, str], news_rows.NewsRow] = {}
    missing_items: list[tuple[str, str]] = []
    for action in news.actions:
        for row in _list(action["test_rows"], "actions.test_rows"):
            values = _list(row, "actions.test_rows[]")
            item_key = (str(values[0]), str(values[1]))
            if item_key in news_items:
                used_items[item_key] = news_items[item_key]
            else:
                missing_items.append(item_key)
    if missing_items:
        listing = ", ".join(f"{item_id}:{ticker}" for item_id, ticker in sorted(set(missing_items)))
        raise AgentsError(
            f"{paths['news_actions']}: test rows without a news_rows.jsonl row: {listing}"
        )
    bull = _bull(paths["bull_mode"])
    stops, sector = _stops_and_sector_rejections(paths["jsonl"])
    for call in manager:
        stop_key = (str(call.raw["date"]), int(call.raw["stopped_asset_id"]))
        if stop_key not in stops:
            raise AgentsError(
                f"{paths['manager_calls']}:{call.line}: call has no detail stop {stop_key}"
            )
    for text in narrator:
        if text.raw["kind"] != "stop":
            continue
        stop_key = (str(text.raw["source_date"]), int(text.raw["source_asset_id"]))
        if stop_key not in stops:
            raise AgentsError(
                f"{paths['narrator']}:{text.line}: stop text has no detail stop {stop_key}"
            )
    news_dates = {str(item["decision_date"]) for item in news.dates}
    bull_dates = {str(item["date"]) for item in bull.decisions}
    if news_dates != bull_dates:
        raise AgentsError(f"{window}: news dates and bull-mode dates differ")
    counts = _counts(news, manager, narrator, bull, sector)
    return WindowData(window, manager, narrator, news, used_items, bull, counts, hashes, run, stops)


def load_delivery(
    label: str, directory: str | Path, windows: Sequence[str] | None = None
) -> Delivery:
    """Verify and parse the selected windows; a missing or changed file stops the run."""
    if not re.fullmatch(RUN_LABEL_PATTERN, label):
        raise AgentsError(f"run label {label!r} does not match {RUN_LABEL_PATTERN}")
    root = _delivery_root(Path(directory))
    manifest_path = root / MANIFEST_NAME
    manifest = _load_json(manifest_path)
    if manifest.get("label") != label:
        raise AgentsManifestError(
            f"{manifest_path}: label is {manifest.get('label')!r}, the command says {label!r}"
        )
    sums = read_manifest(root / SUMS_NAME)
    selected = tuple(windows) if windows else WINDOWS
    unknown = sorted(set(selected) - set(WINDOWS))
    if unknown:
        raise AgentsError(f"unknown window(s): {', '.join(unknown)}")
    news_items = _news_item_index(root, manifest, sums)
    data = tuple(
        _window(root, window, _manifest_run(manifest, window), sums, news_items)
        for window in selected
    )
    controls = _mapping(manifest.get("control_counts"), "manifest.control_counts")
    control = _mapping(controls.get(CONFIGURATION), f"manifest.control_counts.{CONFIGURATION}")
    for item in data:
        expected = _mapping(control.get(item.window), f"control_counts.{item.window}")
        actual = item.counts.as_dict()
        for key, value in actual.items():
            if key not in expected:
                continue
            if expected[key] != value:
                raise AgentsManifestError(
                    f"{manifest_path}: control_counts.{item.window}.{key} is {expected[key]!r}, "
                    f"the file derives {value!r}"
                )
    return Delivery(label, root, manifest_path, data)


