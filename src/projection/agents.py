def _narrator_text(number: int, raw: Mapping[str, Any], where: str) -> NarratorText:
    kind = _text(raw.get("kind"), f"{where}.kind")
    if kind not in NARRATOR_KINDS:
        raise AgentsError(f"{where}.kind: {kind!r} is not a narrator kind")
    _date(raw.get("date"), f"{where}.date")
    _positive_int(raw.get("asset_id"), f"{where}.asset_id")
    source = _text(raw.get("source"), f"{where}.source")
    if source not in ("model", "template"):
        raise AgentsError(f"{where}.source: {source!r} is not model or template")
    generated = _bool(
        raw.get("generated_by_language_model"), f"{where}.generated_by_language_model"
    )
    if generated != (source == "model"):
        raise AgentsError(f"{where}: source {source!r} and generated flag {generated} disagree")
    _text(raw.get("text"), f"{where}.text")
    for key in ("prompt_sha256", "template_sha256"):
        _sha(raw.get(key), f"{where}.{key}")
    model = _mapping(raw.get("model"), f"{where}.model")
    for key in ("requested", "resolved", "revision", "reasoning_effort"):
        _text(model.get(key), f"{where}.model.{key}")
    _bool(model.get("reasoning_effort_used"), f"{where}.model.reasoning_effort_used")
    validator = _mapping(raw.get("validator"), f"{where}.validator")
    _bool(validator.get("passed"), f"{where}.validator.passed")
    _text(validator.get("detail"), f"{where}.validator.detail")
    for key in ("source_kind", "source_date", "source_asset_id", "source_line"):
        if key not in raw:
            raise AgentsError(f"{where}: missing {key}")
    _text(raw.get("source_kind"), f"{where}.source_kind")
    _date(raw.get("source_date"), f"{where}.source_date")
    _positive_int(raw.get("source_asset_id"), f"{where}.source_asset_id")
    _positive_int(raw.get("source_line"), f"{where}.source_line")
    for index, value in enumerate(_list(raw.get("omitted_fields"), f"{where}.omitted_fields")):
        _text(value, f"{where}.omitted_fields[{index}]")
    return NarratorText(number, raw)


def _narrator_texts(path: Path) -> tuple[NarratorText, ...]:
    rows = tuple(
        _narrator_text(number, raw, f"{path}:{number}") for number, raw in _load_jsonl(path)
    )
    keys = [(str(row.raw["kind"]), str(row.raw["date"]), int(row.raw["asset_id"])) for row in rows]
    if len(keys) != len(set(keys)):
        raise AgentsError(f"{path}: duplicate (kind, date, asset_id) key")
    return rows


