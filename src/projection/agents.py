def _stops_and_sector_rejections(path: Path) -> tuple[frozenset[tuple[str, int]], int]:
    """The stop keys and the level-C sector-rejection sum, from the detail JSON Lines.

    Block F does not project the detail file; it reads it only to cross-check that every manager
    call answers a real stop and to derive the manifest's ``news_sector_rejections`` count.
    """
    stops: set[tuple[str, int]] = set()
    sector = 0
    for number, raw in _load_jsonl(path):
        if raw.get("kind") == "stop":
            try:
                stops.add((str(raw["date"]), int(raw["asset_id"])))
            except (KeyError, TypeError, ValueError) as exc:
                raise AgentsError(f"{path}:{number}: malformed stop: {exc}") from exc
        counts = raw.get("eligible_counts")
        if isinstance(counts, Mapping):
            value = counts.get("news_sector")
            if value is not None:
                sector += _non_negative_int(value, f"{path}:{number}.eligible_counts.news_sector")
    return frozenset(stops), sector


