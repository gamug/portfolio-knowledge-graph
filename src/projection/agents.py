def _project_news(  # noqa: C901, PLR0912, PLR0915 -- one graph per source file
    data: WindowData,
    label: str,
    configuration: rdflib.URIRef = KG.Configuration_SystemWithHierarchy,
) -> GraphBuilder:
    """The news actions, date records, levels and evidence of one window.

    ``configuration`` is the book the records belong to: the final delivery's
    ``SYSTEM_WITH_HIERARCHY`` or the live day's ``SYSTEM_LIVE`` (Work item 50).
    """
    builder = GraphBuilder()
    raw = data.news.raw
    run = news_run_iri(label, data.window)
    first_date = min(str(item["decision_date"]) for item in data.news.dates)
    builder.add(run, RDF.type, KG.NewsRunRecord)
    builder.add(run, KG.knowledgeDate, _date_literal(first_date))
    builder.add(run, KG.windowId, rdflib.Literal(data.window))
    builder.add(run, KG.agentRecordOfConfiguration, configuration)
    builder.add(run, KG.newsMode, rdflib.Literal(raw["news_mode"]))
    builder.add(run, KG.newsAlpha, _decimal_literal(raw["news_alpha"]))
    builder.add(run, KG.newsTableSha256, rdflib.Literal(raw["news_table_sha256"]))
    builder.add(run, KG.newsExits, _integer_literal(int(raw["levels_v2"]["b_news_exits"])))
    builder.add(
        run,
        KG.newsSectorRejections,
        _integer_literal(data.counts.news_sector_rejections),
    )
    builder.add(run, KG.newsDateCount, _integer_literal(len(data.news.dates)))
    builder.add(
        run,
        KG.newsRunSessions,
        _integer_literal(len(_list(raw["levels_v2"]["sessions"], "levels_v2.sessions"))),
    )
    builder.add(run, KG.runId, rdflib.Literal(str(raw["run_id"])))
    builder.add(run, KG.sourceDocument, rdflib.Literal(str(data.run["news_actions_file"])))
    builder.add(run, KG.sourceJsonPointer, rdflib.Literal("/"))
    builder.add(run, KG.recordSourceSha256, rdflib.Literal(data.hashes["news_actions"]))

    levels = {str(item["date"]): item for item in data.news.levels}
    fill_by_key = {
        (str(item["decision_date"]), int(item["replaces"])): item for item in data.news.fills
    }
    for index, date in enumerate(data.news.dates):
        day = str(date["decision_date"])
        iri = date_record_iri(label, data.window, day)
        level = levels[day]
        builder.add(iri, RDF.type, KG.DateRecord)
        builder.add(iri, KG.knowledgeDate, _date_literal(day))
        builder.add(iri, KG.windowId, rdflib.Literal(data.window))
        builder.add(iri, KG.dateRecordDate, _date_literal(day))
        builder.add(iri, KG.dateRecordOfRun, run)
        coverage = date["coverage"]
        builder.add(iri, KG.coverageFirst, _date_literal(coverage["first_session"]))
        builder.add(iri, KG.coverageLast, _date_literal(coverage["last_session"]))
        builder.add(
            iri, KG.hasTemporalCoverage, _boolean_literal(bool(date["has_temporal_coverage"]))
        )
        for key, predicate in (
            ("admitted", KG.admittedCount),
            ("admitted_in_base_window", KG.admittedInBaseWindow),
            ("admitted_in_evidence_window", KG.admittedInEvidenceWindow),
            ("sentiment_checked", KG.sentimentChecked),
            ("sentiment_checked_known", KG.sentimentCheckedKnown),
            ("missing_body_hash", KG.missingBodyHash),
            ("undated", KG.undatedCount),
            ("untickered", KG.untickeredCount),
        ):
            builder.add(iri, predicate, _integer_literal(int(date[key])))
        builder.add(iri, KG.poolSize, _integer_literal(len(_list(date["pool"], "pool"))))
        builder.add(iri, KG.completePool, _boolean_literal(bool(date["complete_pool"])))
        for value in date["dropped_conditions"]:
            builder.add(iri, KG.droppedCondition, rdflib.Literal(value))
        builder.add(
            iri,
            KG.surplusPromotionCount,
            _integer_literal(len(_list(date["surplus_promotions"], "surplus_promotions"))),
        )
        rejected = date["rejected_by_cause"]
        builder.add(
            iri,
            KG.rejectedDuplicate,
            _integer_literal(int(rejected.get("duplicate", 0))),
        )
        base = date["base_rates"]
        for value, num_pred, den_pred in (
            (
                base["pooled_negative"],
                KG.baseRatePooledNegativeNumerator,
                KG.baseRatePooledNegativeDenominator,
            ),
            (
                base["pooled_positive"],
                KG.baseRatePooledPositiveNumerator,
                KG.baseRatePooledPositiveDenominator,
            ),
        ):
            numerator, denominator = _fraction(value, "base_rates")
            builder.add(iri, num_pred, _integer_literal(numerator))
            builder.add(iri, den_pred, _integer_literal(denominator))
        builder.add(iri, KG.baseRateTotalRows, _integer_literal(int(base["total_rows"])))
        builder.add(iri, KG.baseRateSignalPossible, _boolean_literal(bool(base["signal_possible"])))
        expected = date["expected"]
        for value, num_pred, den_pred in (
            (expected["total"], KG.expectedTotalNumerator, KG.expectedTotalDenominator),
            (expected["negative"], KG.expectedNegativeNumerator, KG.expectedNegativeDenominator),
            (expected["positive"], KG.expectedPositiveNumerator, KG.expectedPositiveDenominator),
        ):
            numerator, denominator = _fraction(value, "expected")
            builder.add(iri, num_pred, _integer_literal(numerator))
            builder.add(iri, den_pred, _integer_literal(denominator))
        builder.add(iri, KG.expectedLowerBound, _boolean_literal(bool(expected["lower_bound"])))
        builder.add(iri, KG.expectedTests, _integer_literal(int(expected["tests"])))
        builder.add(iri, KG.levelBThreshold, _decimal_literal(level["b_threshold"]))
        c_flagged = _list(level["c_flagged"], "c_flagged")
        c_flags = _mapping(level["c_flags"], "c_flags")
        builder.add(iri, KG.levelCDecision, _boolean_literal(bool(c_flagged) or bool(c_flags)))
        builder.add(
            iri,
            KG.levelCFlaggedCount,
            _integer_literal(len(c_flagged) if c_flagged else len(c_flags)),
        )
        builder.add(iri, KG.levelDFired, _boolean_literal(bool(level["d_fired"])))
        builder.add(iri, KG.levelDTone21, _decimal_literal(level["d_tone21"]))
        builder.add(iri, KG.levelDP20, _decimal_literal(level["d_p20"]))
        inputs = level["filter_inputs"]
        builder.add(iri, KG.filterPriceFlag, _boolean_literal(bool(inputs["price"])))
        builder.add(iri, KG.filterNewsFlag, _boolean_literal(bool(inputs["news"])))
        builder.add(
            iri,
            KG.newsBaseRatesSha256,
            rdflib.Literal(_hash_text(json.dumps(base, sort_keys=True, default=str))),
        )
        builder.add(
            iri,
            KG.newsLevelCDecisionsSha256,
            rdflib.Literal(
                _hash_text(json.dumps(level["c_thresholds"], sort_keys=True, default=str))
            ),
        )
        builder.add(iri, KG.sourceDocument, rdflib.Literal(str(data.run["news_actions_file"])))
        builder.add(iri, KG.sourceJsonPointer, rdflib.Literal(f"/dates/{index}"))
        builder.add(iri, KG.recordSourceSha256, rdflib.Literal(data.hashes["news_actions"]))

    for index, action in enumerate(data.news.actions):
        day = str(action["decision_date"])
        asset_id = int(action["asset_id"])
        kind = str(action["action"])
        iri = news_action_iri(label, data.window, day, asset_id, kind)
        evidence = action["evidence"]
        evidence_iri = news_evidence_iri(label, data.window, day, asset_id)
        builder.add(iri, RDF.type, KG.NewsAction)
        builder.add(iri, KG.knowledgeDate, _date_literal(day))
        builder.add(iri, KG.windowId, rdflib.Literal(data.window))
        builder.add(iri, KG.newsActionKind, rdflib.Literal(kind))
        builder.add(iri, KG.newsActionAsset, _asset(data, asset_id))
        builder.add(iri, KG.newsActionTicker, rdflib.Literal(action["ticker"]))
        builder.add(iri, KG.newsActionOfDateRecord, date_record_iri(label, data.window, day))
        builder.add(iri, KG.newsActionOfRun, run)
        builder.add(iri, KG.newsActionEvidence, evidence_iri)
        if action.get("replaces") is not None:
            builder.add(iri, KG.newsReplacesAsset, _asset(data, int(action["replaces"])))
        if action.get("replaced_by") is not None:
            builder.add(iri, KG.newsReplacedByAsset, _asset(data, int(action["replaced_by"])))
        fill = fill_by_key.get((day, asset_id))
        builder.add(iri, KG.newsActionFilled, _boolean_literal(fill is not None))
        if fill is not None:
            builder.add(iri, KG.newsActionFillAsset, _asset(data, int(fill["asset_id"])))
        for row in _test_rows(action, f"actions[{index}]"):
            builder.add(iri, KG.newsTestRow, rdflib.Literal(row))
        builder.add(iri, KG.sourceDocument, rdflib.Literal(str(data.run["news_actions_file"])))
        builder.add(iri, KG.sourceJsonPointer, rdflib.Literal(f"/actions/{index}"))
        builder.add(iri, KG.recordSourceSha256, rdflib.Literal(data.hashes["news_actions"]))

        builder.add(evidence_iri, RDF.type, KG.NewsEvidence)
        builder.add(evidence_iri, KG.windowId, rdflib.Literal(data.window))
        builder.add(evidence_iri, KG.newsEvidenceOfAction, iri)
        builder.add(evidence_iri, KG.newsEvidenceAsset, _asset(data, asset_id))
        builder.add(evidence_iri, KG.newsEvidenceTicker, rdflib.Literal(evidence["ticker"]))
        builder.add(evidence_iri, KG.newsEvidenceState, rdflib.Literal(evidence["state"]))
        builder.add(evidence_iri, KG.newsN, _integer_literal(int(evidence["n"])))
        builder.add(evidence_iri, KG.newsA, _integer_literal(int(evidence["a"])))
        builder.add(evidence_iri, KG.newsB, _integer_literal(int(evidence["b"])))
        builder.add(evidence_iri, KG.newsCovered, _boolean_literal(bool(evidence["covered"])))
        builder.add(
            evidence_iri,
            KG.meanProbabilityMargin,
            _decimal_literal(evidence["mean_probability_margin"]),
        )
        for group, prefix in (
            ("negative_by_tier", "newsNegativeTier"),
            ("neutral_by_tier", "newsNeutralTier"),
            ("positive_by_tier", "newsPositiveTier"),
        ):
            for tier, value in evidence[group].items():
                predicate = KG[f"{prefix}{tier}"]
                builder.add(evidence_iri, predicate, _integer_literal(int(value)))
        test = evidence["test"]
        for key, predicate in (
            ("statistic_negative", KG.newsStatisticNegative),
            ("statistic_positive", KG.newsStatisticPositive),
            ("critical_negative", KG.newsCriticalNegative),
            ("critical_positive", KG.newsCriticalPositive),
        ):
            if test.get(key) is not None:
                builder.add(evidence_iri, predicate, _integer_literal(int(test[key])))
        for key, num_pred, den_pred in (
            ("p_negative", KG.newsPNegativeNumerator, KG.newsPNegativeDenominator),
            ("p_positive", KG.newsPPositiveNumerator, KG.newsPPositiveDenominator),
            ("size_negative", KG.newsSizeNegativeNumerator, KG.newsSizeNegativeDenominator),
            ("size_positive", KG.newsSizePositiveNumerator, KG.newsSizePositiveDenominator),
        ):
            numerator, denominator = _fraction(test[key], f"test.{key}")
            builder.add(evidence_iri, num_pred, _integer_literal(numerator))
            builder.add(evidence_iri, den_pred, _integer_literal(denominator))
        for key, predicate in (
            ("conflict", KG.newsConflict),
            ("promotion_candidate", KG.newsPromotionCandidate),
            ("veto_candidate", KG.newsVetoCandidate),
        ):
            builder.add(evidence_iri, predicate, _boolean_literal(bool(test[key])))
        builder.add(
            evidence_iri,
            KG.newsBaseRatesSha256,
            rdflib.Literal(_hash_text(json.dumps(test["base_rates"], sort_keys=True, default=str))),
        )
        builder.add(
            evidence_iri,
            KG.newsTestSha256,
            rdflib.Literal(_hash_text(json.dumps(test, sort_keys=True, default=str))),
        )
        builder.add(
            evidence_iri,
            KG.newsTestPointer,
            rdflib.Literal(f"/actions/{index}/evidence/test"),
        )
        for row in _test_rows(evidence, f"actions[{index}].evidence"):
            builder.add(evidence_iri, KG.newsTestRow, rdflib.Literal(row))
            builder.add(evidence_iri, KG.newsItem, _news_item(data, row))
        builder.add(
            evidence_iri,
            KG.sourceDocument,
            rdflib.Literal(str(data.run["news_actions_file"])),
        )
        builder.add(
            evidence_iri, KG.sourceJsonPointer, rdflib.Literal(f"/actions/{index}/evidence")
        )
        builder.add(
            evidence_iri,
            KG.recordSourceSha256,
            rdflib.Literal(data.hashes["news_actions"]),
        )
    return builder


