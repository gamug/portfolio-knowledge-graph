def _news_item_context(rows: Sequence[news_rows.NewsRow]) -> rdflib.Graph:
    """Validation-only block D individuals for the ``:newsItem`` links (never written)."""
    context = rdflib.Graph()
    for row in rows:
        iri = news_rows.news_item_iri(row)
        context.add((iri, RDF.type, KG.NewsItem))
        for predicate, value in (
            (KG.itemKind, rdflib.Literal(row.item_kind)),
            (KG.itemId, rdflib.Literal(row.item_id)),
            (KG.newsTicker, rdflib.Literal(row.ticker)),
            (KG.newsDate, _date_literal(row.date)),
            (KG.dateSource, rdflib.Literal(row.date_source)),
            (KG.newsTitle, rdflib.Literal(row.title)),
            (KG.newsText, rdflib.Literal(row.text)),
            (KG.textSource, rdflib.Literal(row.text_source)),
            (KG.newsSentiment, rdflib.Literal(row.sentiment)),
            (KG.sentimentScore, _decimal_literal(row.sentiment_score)),
            (KG.pPositive, _decimal_literal(row.p_positive)),
            (KG.pNegative, _decimal_literal(row.p_negative)),
            (KG.pNeutral, _decimal_literal(row.p_neutral)),
            (KG.newsCategory, rdflib.Literal(row.category)),
            (KG.categoryScore, _decimal_literal(row.category_score)),
            (KG.groupLabel, rdflib.Literal(row.group_label)),
            (KG.bodyHash, rdflib.Literal(row.body_hash)),
            (KG.modelRevision, rdflib.Literal(row.model_revision)),
            (KG.sentimentRevision, rdflib.Literal(row.sentiment_revision)),
            (KG.categoryRevision, rdflib.Literal(row.category_revision)),
        ):
            context.add((iri, predicate, value))
        if row.article_id is not None:
            context.add((iri, KG.articleId, _integer_literal(row.article_id)))
        if row.source_domain is not None:
            context.add((iri, KG.sourceDomain, rdflib.Literal(row.source_domain)))
        if row.asset_id is not None:
            context.add((iri, KG.newsAssetId, _integer_literal(row.asset_id)))
        if row.asset is not None:
            context.add((iri, KG.newsItemOfAsset, KG[row.asset]))
        if row.url is not None:
            context.add((iri, KG.url, rdflib.URIRef(row.url)))
    return context


def _asset_context(data: WindowData, label: str) -> rdflib.Graph:
    """Validation-only context for a dry run: the assets, stops, book and configuration.

    A real write fetches these from the store. In a dry run the loader types each asset and gives
    it a validation-only placeholder CIK (never written) so `AssetShape` passes without inventing a
    real CIK; each stop gets the required StopEvent fields. None of this is written.
    """
    context = rdflib.Graph()
    context.add((KG.Configuration_SystemWithHierarchy, RDF.type, KG.BacktestConfiguration))
    context.add(
        (
            KG.Configuration_SystemWithHierarchy,
            rdflib.URIRef("http://www.w3.org/2004/02/skos/core#notation"),
            rdflib.Literal("SYSTEM_WITH_HIERARCHY"),
        )
    )
    context.add(
        (
            KG.Configuration_SystemWithHierarchy,
            rdflib.RDFS.label,
            rdflib.Literal("Sistema con la Jerarquía de Veto"),
        )
    )
    context.add(
        (
            KG.Configuration_SystemWithHierarchy,
            rdflib.RDFS.comment,
            rdflib.Literal("SYSTEM_WITH_HIERARCHY"),
        )
    )
    book = KG[f"Book_{label}_{data.window}_context"]
    context.add((book, RDF.type, KG.StrategyBook))
    context.add((book, KG.bookId, _integer_literal(1)))
    context.add((book, KG.backtestRunId, _integer_literal(1)))
    context.add((book, KG.runLabel, rdflib.Literal(label)))
    context.add((book, KG.windowId, rdflib.Literal(data.window)))
    context.add((book, KG.backtestStartDate, _date_literal("1900-01-01")))
    context.add((book, KG.backtestEndDate, _date_literal("2100-01-01")))
    context.add((book, KG.runStatus, rdflib.Literal("completed")))
    context.add((book, KG.armCode, rdflib.Literal("TOPN_MV_GUARD")))
    context.add((book, KG.objective, rdflib.Literal("context")))
    context.add((book, KG.excludeHardVetoed, _boolean_literal(False)))
    context.add((book, KG.knowledgeDate, _date_literal("1900-01-01")))
    for asset_id, ticker in data.news.tickers.items():
        if not _LOCAL.fullmatch(ticker):
            continue
        asset = KG[ticker]
        context.add((asset, RDF.type, KG.Asset))
        context.add((asset, KG.tickerSymbol, rdflib.Literal(ticker)))
        # A validation-only placeholder so AssetShape's CIK branch passes without inventing a
        # real CIK or a membership whose Universe is three hops from the batch's reference.
        context.add((asset, KG.cikNumber, rdflib.Literal("0000000000")))
        _ = asset_id
    for triple in _news_item_context(tuple(data.news_items.values())):
        context.add(triple)
    for day, asset_id in data.stops:
        stop = stop_iri(label, data.window, day, asset_id)
        context.add((stop, RDF.type, KG.StopEvent))
        context.add((stop, KG.stopOfBook, book))
        context.add((stop, KG.stopDate, _date_literal(day)))
        context.add((stop, KG.stoppedAsset, _asset(data, asset_id)))
        context.add((stop, KG.stopWeightBefore, _decimal_literal(Decimal(0))))
        context.add((stop, KG.filterState, _boolean_literal(False)))
        context.add((stop, KG.filterDecisionDate, _date_literal(day)))
        context.add((stop, KG.exposureScale, _decimal_literal(Decimal(1))))
        context.add((stop, KG.rhoW0, _decimal_literal(Decimal(0))))
        context.add((stop, KG.rho, _decimal_literal(Decimal(0))))
        context.add((stop, KG.chooser, rdflib.Literal("agent")))
        context.add((stop, KG.cashLeft, _decimal_literal(Decimal(0))))
        context.add((stop, KG.portfolioCheckPassed, _boolean_literal(True)))
        context.add((stop, KG.chosenCash, _boolean_literal(True)))
        context.add((stop, KG.knowledgeDate, _date_literal(day)))
    return context


def expected_counts(data: WindowData) -> Mapping[str, int]:
    return {
        "manager_calls": data.counts.manager_calls,
        "manager_fallbacks": data.counts.manager_fallbacks,
        "manager_repairs": data.counts.manager_repairs,
        "narrator_texts": data.counts.narrator_texts,
        "news_actions": len(data.news.actions),
        "news_veto": data.counts.news_pool_actions["veto"],
        "news_promotion": data.counts.news_pool_actions["promotion"],
        "news_dates": data.counts.news_date_records,
        "news_level_c": data.counts.news_level_c_decisions,
        "news_level_d": data.counts.news_level_d_decisions,
        "news_exits": data.counts.news_exits,
        "news_sector_rejections": data.counts.news_sector_rejections,
        "bull_decisions": len(data.bull.decisions),
        "bull_triggered": data.counts.bull_triggered,
    }


def _scalar(store: ReadableStore, query: str) -> int:
    rows = store.select(query)
    if not rows or "n" not in rows[0]:
        raise AgentsError(f"store query returned no count: {query}")
    return int(rows[0]["n"])


def _graph_exists(store: ReadableStore, graph: str) -> bool:
    return bool(store.select(f"SELECT * WHERE {{ GRAPH <{graph}> {{ ?s ?p ?o }} }} LIMIT 1"))


_PREFIX = "PREFIX : <https://thesis.local/kg/portfolio#>\n"


def verify_stored(
    store: ReadableStore, label: str, data: WindowData, *, only: Sequence[str] | None = None
) -> list[Check]:
    """Compare the stored counts of the selected graphs with the parsed files."""
    checks: list[Check] = []
    expected = expected_counts(data)
    slugs = tuple(only) if only is not None else SLUGS
    for slug in slugs:
        graph = graph_name(label, data.window, slug)
        if not _graph_exists(store, graph):
            checks.append(Check(f"stored {graph}", True, "not store-verifiable: graph is absent"))
            continue
        problems: list[str] = []
        if slug == "manager_calls":
            values = {
                "manager_calls": _scalar(
                    store,
                    _PREFIX
                    + f"SELECT (COUNT(DISTINCT ?s) AS ?n) WHERE {{ GRAPH <{graph}> {{ ?s a :ManagerCall }} }}",
                ),
                "manager_fallbacks": _scalar(
                    store,
                    _PREFIX
                    + f'SELECT (COUNT(DISTINCT ?s) AS ?n) WHERE {{ GRAPH <{graph}> {{ ?s a :ManagerCall ; :fallbackUsedRule "true"^^<{XSD.boolean}> }} }}',
                ),
                "manager_repairs": _scalar(
                    store,
                    _PREFIX
                    + f'SELECT (COUNT(DISTINCT ?s) AS ?n) WHERE {{ GRAPH <{graph}> {{ ?s a :ManagerCall ; :repairUsed "true"^^<{XSD.boolean}> }} }}',
                ),
            }
            want = {key: expected[key] for key in values}
            problems = [
                f"{key}: stored {got}, expected {want[key]}"
                for key, got in values.items()
                if got != want[key]
            ]
        elif slug == "narrator":
            got = _scalar(
                store,
                _PREFIX
                + f"SELECT (COUNT(DISTINCT ?s) AS ?n) WHERE {{ GRAPH <{graph}> {{ ?s a :NarratorText }} }}",
            )
            if got != expected["narrator_texts"]:
                problems.append(
                    f"narrator_texts: stored {got}, expected {expected['narrator_texts']}"
                )
        elif slug == "news":
            values = {
                "news_actions": _scalar(
                    store,
                    _PREFIX
                    + f"SELECT (COUNT(DISTINCT ?s) AS ?n) WHERE {{ GRAPH <{graph}> {{ ?s a :NewsAction }} }}",
                ),
                "news_dates": _scalar(
                    store,
                    _PREFIX
                    + f"SELECT (COUNT(DISTINCT ?s) AS ?n) WHERE {{ GRAPH <{graph}> {{ ?s a :DateRecord }} }}",
                ),
                "news_level_c": _scalar(
                    store,
                    _PREFIX
                    + f'SELECT (COUNT(DISTINCT ?s) AS ?n) WHERE {{ GRAPH <{graph}> {{ ?s a :DateRecord ; :levelCDecision "true"^^<{XSD.boolean}> }} }}',
                ),
                "news_level_d": _scalar(
                    store,
                    _PREFIX
                    + f'SELECT (COUNT(DISTINCT ?s) AS ?n) WHERE {{ GRAPH <{graph}> {{ ?s a :DateRecord ; :levelDFired "true"^^<{XSD.boolean}> }} }}',
                ),
                "news_exits": _scalar(
                    store,
                    _PREFIX
                    + f"SELECT (SUM(?value) AS ?n) WHERE {{ GRAPH <{graph}> {{ ?s a :NewsRunRecord ; :newsExits ?value }} }}",
                ),
                "news_sector_rejections": _scalar(
                    store,
                    _PREFIX
                    + f"SELECT (SUM(?value) AS ?n) WHERE {{ GRAPH <{graph}> {{ ?s a :NewsRunRecord ; :newsSectorRejections ?value }} }}",
                ),
            }
            want = {key: expected[key] for key in values}
            problems = [
                f"{key}: stored {got}, expected {want[key]}"
                for key, got in values.items()
                if got != want[key]
            ]
            for kind in ("veto", "promotion"):
                got = _scalar(
                    store,
                    _PREFIX
                    + f'SELECT (COUNT(DISTINCT ?s) AS ?n) WHERE {{ GRAPH <{graph}> {{ ?s a :NewsAction ; :newsActionKind "{kind}" }} }}',
                )
                key = f"news_{kind}"
                if got != expected[key]:
                    problems.append(f"{key}: stored {got}, expected {expected[key]}")
        elif slug == "bull_mode":
            values = {
                "bull_decisions": _scalar(
                    store,
                    _PREFIX
                    + f"SELECT (COUNT(DISTINCT ?s) AS ?n) WHERE {{ GRAPH <{graph}> {{ ?s a :BullModeDecision }} }}",
                ),
                "bull_triggered": _scalar(
                    store,
                    _PREFIX
                    + f'SELECT (COUNT(DISTINCT ?s) AS ?n) WHERE {{ GRAPH <{graph}> {{ ?s a :BullModeDecision ; :bullTriggered "true"^^<{XSD.boolean}> }} }}',
                ),
            }
            want = {key: expected[key] for key in values}
            problems = [
                f"{key}: stored {got}, expected {want[key]}"
                for key, got in values.items()
                if got != want[key]
            ]
        checks.append(
            Check(
                f"stored {graph}",
                not problems,
                "counts match" if not problems else "; ".join(problems),
            )
        )
    return checks


# --- CLI ----------------------------------------------------------------------------------------

_ONLY = ("manager_calls", "narrator", "news", "bull_mode")


def _label_arg(text: str) -> str:
    if not re.fullmatch(RUN_LABEL_PATTERN, text):
        raise argparse.ArgumentTypeError(
            f"run label {text!r} does not match {RUN_LABEL_PATTERN} (as in final)"
        )
    return text


def _window_arg(text: str) -> str:
    if text not in WINDOWS:
        raise argparse.ArgumentTypeError(f"window {text!r} is not one of {', '.join(WINDOWS)}")
    return text


def _only_arg(text: str) -> str:
    if text not in _ONLY:
        raise argparse.ArgumentTypeError(f"--only {text!r} is not one of {', '.join(_ONLY)}")
    return text


def _batch_size(text: str) -> int:
    try:
        value = int(text)
    except ValueError as exc:
        raise argparse.ArgumentTypeError("batch size must be a positive integer") from exc
    if value < 1:
        raise argparse.ArgumentTypeError("batch size must be a positive integer")
    return value


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--label", required=True, type=_label_arg, help="the run label (final)")
    parser.add_argument(
        "--dir",
        type=Path,
        default=None,
        metavar="DIR",
        help=f"the delivery root (default: KG_DELIVERY_DIR or {DEFAULT_DELIVERY})",
    )
    parser.add_argument(
        "--window",
        action="append",
        type=_window_arg,
        default=None,
        metavar="WINDOW",
        help="load only this window (repeatable; default: all seven)",
    )
    parser.add_argument(
        "--only",
        action="append",
        type=_only_arg,
        default=None,
        metavar="SLUG",
        help="load only this file type (repeatable; default: all four)",
    )
    parser.add_argument("--write", action="store_true", help="append the selected graphs")
    parser.add_argument(
        "--check-store",
        action="store_true",
        help="read the live store, run the same gate plans, write nothing",
    )
    parser.add_argument(
        "--to-production",
        action="store_true",
        help="with --write: allow the production repository (a maintainer decision)",
    )
    parser.add_argument(
        "--batch-size",
        type=_batch_size,
        default=BATCH_SIZE,
        metavar="N",
        help=f"N-Triples per write request (default {BATCH_SIZE})",
    )
    args = parser.parse_args(argv)
    if args.check_store and args.write:
        parser.error("--check-store only reads; do not combine it with --write")
    if args.check_store and args.to_production:
        parser.error("--check-store never writes; drop --to-production")
    if args.to_production and not args.write:
        parser.error("--to-production only matters with --write")
    args.dir = args.dir or Path(os.environ.get("KG_DELIVERY_DIR", DEFAULT_DELIVERY))
    return args


def open_store(args: argparse.Namespace) -> GraphDB | None:
    if not (args.write or args.check_store):
        return None
    store = GraphDB.from_env()
    if args.write and store.repository == PRODUCTION_REPOSITORY and not args.to_production:
        print(
            "--write to the production repository needs --to-production: the final label is the "
            "maintainer's decision",
            file=sys.stderr,
        )
        raise SystemExit(2)
    return store


def _show_build(
    delivery: Delivery, builders: Mapping[str, Mapping[str, GraphBuilder]], only: Sequence[str]
) -> None:
    print(f"label: {delivery.label}")
    print(f"manifest: {delivery.manifest}")
    total = 0
    for data in delivery.windows:
        print(f"window: {data.window}")
        print(
            "counts: " + ", ".join(f"{key}={value}" for key, value in data.counts.as_dict().items())
        )
        for slug in only:
            graph = graph_name(delivery.label, data.window, slug)
            count = len(builders[data.window][slug])
            total += count
            print(f"graph: {graph}: {count} triples")
    print(f"triples: total {total}")


def _validate(
    delivery: Delivery,
    builders: Mapping[str, Mapping[str, GraphBuilder]],
    only: Sequence[str],
) -> int:
    for data in delivery.windows:
        context = _asset_context(data, delivery.label)
        for slug in only:
            graph = graph_name(delivery.label, data.window, slug)
            try:
                parsed = gate.parse_batch(builders[data.window][slug].turtle())
                gate.validate(parsed, context=context)
            except gate.IngestRejected as exc:
                print(f"SHACL: FAIL {graph}\n{exc}")
                return 1
            print(f"SHACL: conforms ({graph}, gate.validate)")
    return 0


def _plan(
    store: GraphDB,
    delivery: Delivery,
    builders: Mapping[str, Mapping[str, GraphBuilder]],
    only: Sequence[str],
) -> dict[str, gate.IngestPlan]:
    plans: dict[str, gate.IngestPlan] = {}
    for data in delivery.windows:
        for slug in only:
            graph = graph_name(delivery.label, data.window, slug)
            # The store is the context: assets, stops and block-D NewsItems must already be
            # loaded. _asset_context is a dry-run-only helper and must never be merged here:
            # its placeholder :cikNumber would collide with the real one and break AssetShape.
            plans[graph] = gate.plan(store, builders[data.window][slug].turtle(), graph)
    return plans


def _show_plan(plans: Mapping[str, gate.IngestPlan]) -> None:
    for graph, plan in plans.items():
        print(f"pre-flight: {graph}: {plan.status.value}")


def _show_checks(checks: Sequence[Check]) -> bool:
    ok = True
    for check in checks:
        print(f"{'PASS' if check.passed else 'FAIL'}  {check.name}: {check.detail}")
        ok = ok and check.passed
    return ok


def _write_graph(store: GraphDB, plan: gate.IngestPlan, batch_size: int) -> int:
    try:
        return gate.write_batched(store, plan, batch_size=batch_size)
    except gate.WriteInDoubt as exc:
        print(
            f"store error, the graph is in doubt: {exc}\n{plan.graph} may be partially or fully "
            "written; do not retry blindly",
            file=sys.stderr,
        )
        raise
    except gate.IngestRejected as exc:
        print(f"STOPPED\n{exc}", file=sys.stderr)
        raise


def main(  # noqa: C901, PLR0912 -- one return per mode
    argv: Sequence[str] | None = None,
) -> int:
    args = parse_args(argv)
    started = time.perf_counter()
    only = tuple(args.only) if args.only else SLUGS
    try:
        if args.check_store or args.write:
            announce_target(GraphDB.from_env())
        delivery = load_delivery(args.label, args.dir, args.window)
        builders = {data.window: project(data, args.label) for data in delivery.windows}
        _show_build(delivery, builders, only)
        print(f"timing: manifest+parse {time.perf_counter() - started:.3f} s")
        if not args.write and not args.check_store:
            code = _validate(delivery, builders, only)
            print(f"timing: SHACL {time.perf_counter() - started:.3f} s")
            return code
        store = open_store(args)
        assert store is not None
        try:
            plans = _plan(store, delivery, builders, only)
        except gate.IngestRejected as exc:
            print(f"STOPPED\n{exc}", file=sys.stderr)
            return 1
        _show_plan(plans)
        if args.check_store:
            checks: list[Check] = []
            for data in delivery.windows:
                existing = [
                    slug
                    for slug in only
                    if plans[graph_name(args.label, data.window, slug)].status
                    is gate.IngestPlanStatus.ALREADY_IN_STORE
                ]
                if existing:
                    checks.extend(verify_stored(store, args.label, data, only=existing))
                else:
                    for slug in only:
                        checks.append(
                            Check(
                                f"stored {graph_name(args.label, data.window, slug)}",
                                True,
                                "not store-verifiable: graph is absent",
                            )
                        )
            code = 0 if _show_checks(checks) else 1
            print(f"timing: total {time.perf_counter() - started:.3f} s")
            return code
        written = 0
        for graph, plan in plans.items():
            if plan.status is gate.IngestPlanStatus.ALREADY_IN_STORE:
                print(f"already-in-the-store (skipped): {graph}")
                continue
            try:
                count = _write_graph(store, plan, args.batch_size)
            except (gate.WriteInDoubt, gate.IngestRejected):
                return 1
            written += count
            print(f"written: {graph}: {count} triples")
        print(f"timing: gate write {time.perf_counter() - started:.3f} s")
        checks = []
        for data in delivery.windows:
            checks.extend(verify_stored(store, args.label, data, only=only))
        ok = _show_checks(checks)
        print(f"written: total {written} triples")
        print(f"timing: total {time.perf_counter() - started:.3f} s")
        return 0 if ok else 1  # noqa: TRY300 -- the success return pairs with the failure handlers
    except (AgentsError, ManifestError, GraphDBError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
