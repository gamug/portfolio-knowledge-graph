def _news_evidence(  # noqa: C901 -- one source contract read in one place
    raw: Mapping[str, Any], where: str
) -> Mapping[str, Any]:
    _positive_int(raw.get("asset_id"), f"{where}.asset_id")
    _text(raw.get("ticker"), f"{where}.ticker")
    _text(raw.get("state"), f"{where}.state")
    for key in ("n", "a", "b"):
        _non_negative_int(raw.get(key), f"{where}.{key}")
    _bool(raw.get("covered"), f"{where}.covered")
    _decimal(raw.get("mean_probability_margin"), f"{where}.mean_probability_margin")
    for group in ("negative_by_tier", "neutral_by_tier", "positive_by_tier"):
        tiers = _mapping(raw.get(group), f"{where}.{group}")
        for tier, value in tiers.items():
            _non_negative_int(value, f"{where}.{group}.{tier}")
    test = _mapping(raw.get("test"), f"{where}.test")
    for key in ("statistic_negative", "statistic_positive"):
        _int(test.get(key), f"{where}.test.{key}")
    for key in ("critical_negative", "critical_positive"):
        if test.get(key) is not None:
            _int(test[key], f"{where}.test.{key}")
    for key in ("p_negative", "p_positive", "size_negative", "size_positive"):
        _fraction(test.get(key), f"{where}.test.{key}")
    for key in ("conflict", "promotion_candidate", "veto_candidate"):
        _bool(test.get(key), f"{where}.test.{key}")
    _mapping(test.get("base_rates"), f"{where}.test.base_rates")
    rows = _list(raw.get("test_rows"), f"{where}.test_rows")
    for index, row in enumerate(rows):
        values = _list(row, f"{where}.test_rows[{index}]")
        if len(values) != TEST_ROW_WIDTH:
            raise AgentsError(f"{where}.test_rows[{index}]: expected [item_id, ticker]")
        _news_test_item_id(values[0], f"{where}.test_rows[{index}][0]")
        _text(values[1], f"{where}.test_rows[{index}][1]")
    return raw


def _news_test_item_id(value: Any, where: str) -> None:
    """A sub_news integer id or a body's 64-lowercase-hex fingerprint; no empty strings."""
    if isinstance(value, int) and not isinstance(value, bool):
        _positive_int(value, where)
        return
    if isinstance(value, str) and _BODY_ID.fullmatch(value):
        return
    raise AgentsError(f"{where}: expected a positive integer or 64 lowercase hex characters")


def _news_action(raw: Mapping[str, Any], where: str) -> Mapping[str, Any]:
    action = _text(raw.get("action"), f"{where}.action")
    if action not in ("veto", "promotion"):
        raise AgentsError(f"{where}.action: {action!r} is not veto or promotion")
    _date(raw.get("decision_date"), f"{where}.decision_date")
    _positive_int(raw.get("asset_id"), f"{where}.asset_id")
    _text(raw.get("ticker"), f"{where}.ticker")
    for key in ("replaces", "replaced_by"):
        if raw.get(key) is not None:
            _positive_int(raw[key], f"{where}.{key}")
    evidence = _news_evidence(
        _mapping(raw.get("evidence"), f"{where}.evidence"), f"{where}.evidence"
    )
    rows = _list(raw.get("test_rows"), f"{where}.test_rows")
    if len(rows) != len(_list(evidence["test_rows"], f"{where}.evidence.test_rows")):
        raise AgentsError(f"{where}: top-level and evidence test_rows differ")
    return raw


