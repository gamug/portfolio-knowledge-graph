# --- scalar parsing -----------------------------------------------------------------------------


def _text(value: object, where: str) -> str:
    if not isinstance(value, str) or not value:
        raise AgentsError(f"{where}: expected a non-empty string, got {value!r}")
    return value


def _optional_text(value: object, where: str) -> str | None:
    if value is None or value == "":
        return None
    return _text(value, where)


def _sha(value: object, where: str, *, optional: bool = False) -> str | None:
    if value is None and optional:
        return None
    text = _text(value, where)
    if not SHA256.fullmatch(text):
        raise AgentsError(f"{where}: {text!r} is not a lowercase SHA-256")
    return text


def _int(value: object, where: str) -> int:
    if isinstance(value, bool):
        raise AgentsError(f"{where}: expected an integer, got a boolean")
    if isinstance(value, int):
        return value
    if isinstance(value, Decimal) and value.is_finite() and value == value.to_integral_value():
        return int(value)
    raise AgentsError(f"{where}: expected an integer, got {value!r}")


def _positive_int(value: object, where: str) -> int:
    number = _int(value, where)
    if number < 1:
        raise AgentsError(f"{where}: expected a positive integer, got {number}")
    return number


def _non_negative_int(value: object, where: str) -> int:
    number = _int(value, where)
    if number < 0:
        raise AgentsError(f"{where}: expected a non-negative integer, got {number}")
    return number


def _bool(value: object, where: str) -> bool:
    if not isinstance(value, bool):
        raise AgentsError(f"{where}: expected a boolean, got {value!r}")
    return value


def _decimal(value: object, where: str) -> Decimal:
    if isinstance(value, bool):
        raise AgentsError(f"{where}: expected a decimal, got a boolean")
    if isinstance(value, Decimal):
        number = value
    elif isinstance(value, int):
        number = Decimal(value)
    else:
        raise AgentsError(f"{where}: expected a JSON number, got {value!r}")
    if not number.is_finite():
        raise AgentsError(f"{where}: expected a finite decimal, got {value!r}")
    return number


def _date(value: object, where: str) -> datetime.date:
    text = _text(value, where)
    if not _DATE.fullmatch(text):
        raise AgentsError(f"{where}: {text!r} is not a strict YYYY-MM-DD date")
    try:
        day = datetime.date.fromisoformat(text)
    except ValueError as exc:
        raise AgentsError(f"{where}: {text!r} is not a calendar date ({exc})") from exc
    if day.isoformat() != text:
        raise AgentsError(f"{where}: {text!r} is not the ISO form of {day.isoformat()}")
    return day


def _date_text(value: object, where: str) -> str:
    return _date(value, where).isoformat()


def _fraction(value: object, where: str) -> tuple[int, int]:
    text = _text(value, where)
    match = _FRACTION.fullmatch(text)
    if match is None:
        raise AgentsError(f"{where}: {text!r} is not an integer fraction 'num/den'")
    numerator, denominator = int(match.group(1)), int(match.group(2))
    if denominator < 1:
        raise AgentsError(f"{where}: {text!r} has a non-positive denominator")
    return numerator, denominator


def _mapping(value: object, where: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise AgentsError(f"{where}: expected an object, got {type(value).__name__}")
    return value


def _list(value: object, where: str) -> Sequence[Any]:
    if not isinstance(value, list):
        raise AgentsError(f"{where}: expected a list, got {type(value).__name__}")
    return value


def _object_list(value: object, where: str) -> tuple[Mapping[str, Any], ...]:
    return tuple(
        _mapping(item, f"{where}[{index}]") for index, item in enumerate(_list(value, where))
    )


# --- file and manifest --------------------------------------------------------------------------


def _load_json(path: Path) -> Mapping[str, Any]:
    try:
        raw = json.loads(path.read_text(encoding="utf-8"), parse_float=Decimal)
    except (OSError, json.JSONDecodeError) as exc:
        raise AgentsError(f"{path}: {exc}") from exc
    return _mapping(raw, str(path))


def _load_jsonl(path: Path) -> list[tuple[int, Mapping[str, Any]]]:
    rows: list[tuple[int, Mapping[str, Any]]] = []
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise AgentsError(f"{path}: {exc}") from exc
    for number, line in enumerate(lines, 1):
        if not line.strip():
            raise AgentsError(f"{path}:{number}: empty line")
        try:
            raw = json.loads(line, parse_float=Decimal)
        except json.JSONDecodeError as exc:
            raise AgentsError(f"{path}:{number}: {exc}") from exc
        rows.append((number, _mapping(raw, f"{path}:{number}")))
    if not rows:
        raise AgentsError(f"{path}: the file has no rows")
    return rows


def _delivery_root(directory: Path) -> Path:
    directory = directory.resolve()
    if (directory / MANIFEST_NAME).is_file():
        return directory
    for parent in directory.parents:
        if (parent / MANIFEST_NAME).is_file():
            return parent
    raise AgentsManifestError(f"{directory}: no {MANIFEST_NAME} in the directory or a parent")


def _manifest_run(manifest: Mapping[str, Any], window: str) -> Mapping[str, Any]:
    configurations = _list(manifest.get("configurations"), "manifest.configurations")
    for configuration in configurations:
        item = _mapping(configuration, "manifest.configurations[]")
        if item.get("configuration") != CONFIGURATION:
            continue
        runs = _list(item.get("runs"), f"manifest.{CONFIGURATION}.runs")
        for run in runs:
            entry = _mapping(run, f"manifest.{CONFIGURATION}.runs[]")
            if entry.get("window") == window:
                return entry
    raise AgentsManifestError(f"manifest: no {CONFIGURATION} run for window {window}")


def _verify_file(root: Path, relative: str, declared: str, sums: Mapping[str, str]) -> str:
    path = root / relative
    if not path.is_file():
        raise AgentsManifestError(f"{path}: listed in the manifest but the file does not exist")
    if relative not in sums:
        raise AgentsManifestError(f"{path}: not listed in {SUMS_NAME}")
    actual = sha256_file(path)
    if actual != declared:
        raise AgentsManifestError(
            f"{path}: SHA-256 mismatch: manifest says {declared}, the file has {actual}"
        )
    if actual != sums[relative]:
        raise AgentsManifestError(
            f"{path}: SHA-256 mismatch: {SUMS_NAME} says {sums[relative]}, the file has {actual}"
        )
    return actual


# --- manager calls ------------------------------------------------------------------------------


def _manager_call(  # noqa: C901, PLR0912, PLR0915 -- one source contract read in one place
    number: int, raw: Mapping[str, Any], where: str
) -> ManagerCall:
    _non_negative_int(raw.get("call_index"), f"{where}.call_index")
    _date(raw.get("date"), f"{where}.date")
    _positive_int(raw.get("stopped_asset_id"), f"{where}.stopped_asset_id")
    choice = _mapping(raw.get("answer_choice"), f"{where}.answer_choice")
    asset = choice.get("asset_id")
    if asset is not None:
        _positive_int(asset, f"{where}.answer_choice.asset_id")
    _text(choice.get("label"), f"{where}.answer_choice.label")
    fraction = _decimal(choice.get("size_fraction"), f"{where}.answer_choice.size_fraction")
    if not Decimal(0) <= fraction <= Decimal(1):
        raise AgentsError(f"{where}.answer_choice.size_fraction: {fraction} is outside [0, 1]")
    for key in ("is_cash", "is_spy"):
        _bool(choice.get(key), f"{where}.answer_choice.{key}")
    if bool(choice["is_cash"]) and asset is not None:
        raise AgentsError(f"{where}.answer_choice: CASH has no asset_id")
    chosen = _mapping(raw.get("chosen"), f"{where}.chosen")
    _positive_int(chosen.get("asset_id"), f"{where}.chosen.asset_id")
    chosen_fraction = _decimal(chosen.get("size_fraction"), f"{where}.chosen.size_fraction")
    if not Decimal(0) <= chosen_fraction <= Decimal(1):
        raise AgentsError(f"{where}.chosen.size_fraction: {chosen_fraction} is outside [0, 1]")
    _bool(chosen.get("is_spy"), f"{where}.chosen.is_spy")
    label_maps = _mapping(raw.get("label_maps"), f"{where}.label_maps")
    item_map = _mapping(label_maps.get("item_map"), f"{where}.label_maps.item_map")
    label = str(choice["label"])
    if label in item_map:
        mapped = _mapping(item_map[label], f"{where}.label_maps.item_map.{label}")
        if mapped.get("asset_id") != asset:
            raise AgentsError(
                f"{where}: answer label {label} maps to asset {mapped.get('asset_id')!r}, "
                f"the answer says {asset!r}"
            )
    fallback = _mapping(raw.get("fallback"), f"{where}.fallback")
    for key in ("used_rule", "used_cash"):
        _bool(fallback.get(key), f"{where}.fallback.{key}")
    for key in ("cause", "detail"):
        _optional_text(fallback.get(key), f"{where}.fallback.{key}")
    _bool(raw.get("repair_used"), f"{where}.repair_used")
    for key in ("repair_cause", "repair_detail"):
        _optional_text(raw.get(key), f"{where}.{key}")
    model = _mapping(raw.get("model"), f"{where}.model")
    for key in ("requested", "resolved", "revision", "reasoning_effort"):
        _text(model.get(key), f"{where}.model.{key}")
    _bool(model.get("reasoning_effort_used"), f"{where}.model.reasoning_effort_used")
    for key in (
        "prompt_template_sha256",
        "prompt_sha256",
        "tool_outputs_sha256",
        "skill_file_sha256",
    ):
        _sha(raw.get(key), f"{where}.{key}")
    for key in ("system_prompt", "user_prompt", "raw_answer", "raw_message"):
        if not isinstance(raw.get(key), str):
            raise AgentsError(f"{where}.{key}: expected a string")
    if raw.get("first_raw_answer") is not None and not isinstance(raw["first_raw_answer"], str):
        raise AgentsError(f"{where}.first_raw_answer: expected a string or null")
    validator = _mapping(raw.get("validator"), f"{where}.validator")
    _bool(validator.get("passed"), f"{where}.validator.passed")
    _optional_text(validator.get("cause"), f"{where}.validator.cause")
    _text(validator.get("detail"), f"{where}.validator.detail")
    first_validator = raw.get("first_validator")
    if first_validator is not None:
        item = _mapping(first_validator, f"{where}.first_validator")
        _bool(item.get("passed"), f"{where}.first_validator.passed")
        _optional_text(item.get("cause"), f"{where}.first_validator.cause")
        _text(item.get("detail"), f"{where}.first_validator.detail")
    usage = _mapping(raw.get("usage"), f"{where}.usage")
    for key in ("inputTokens", "outputTokens", "totalTokens"):
        _non_negative_int(usage.get(key), f"{where}.usage.{key}")
    for key in ("tool_order", "finish_reasons"):
        values = _list(raw.get(key), f"{where}.{key}")
        for index, value in enumerate(values):
            _text(value, f"{where}.{key}[{index}]")
    _list(raw.get("turns"), f"{where}.turns")
    _list(raw.get("attempts"), f"{where}.attempts")
    _int(raw.get("shuffle_seed"), f"{where}.shuffle_seed")
    if _decimal(raw.get("elapsed_s"), f"{where}.elapsed_s") < 0:
        raise AgentsError(f"{where}.elapsed_s: expected a non-negative decimal")
    return ManagerCall(number, raw)


def _manager_calls(path: Path) -> tuple[ManagerCall, ...]:
    rows = tuple(
        _manager_call(number, raw, f"{path}:{number}") for number, raw in _load_jsonl(path)
    )
    indexes = [int(row.raw["call_index"]) for row in rows]
    if len(indexes) != len(set(indexes)):
        raise AgentsError(f"{path}: duplicate call_index")
    return rows


