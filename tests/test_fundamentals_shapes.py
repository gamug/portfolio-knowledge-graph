def test_only_ebitda_and_nopat_are_usd_metrics() -> None:
    g = tbox()
    comments = {name: str(g.value(KG[name], RDFS.comment)) for name in METRIC_PROPERTIES}
    usd = {name for name, comment in comments.items() if "USD" in comment}
    assert usd == {"ebitda", "nopat"}


def test_the_domain_widening_does_not_drop_an_existing_type() -> None:
    ds = rdflib.Dataset()
    for name in ("tbox.ttl", "shapes.ttl", "reference.ttl", "rules.ttl", "labels.ttl"):
        ds.parse(SCHEMA / name, format="turtle")
    ds.parse(SCHEMA / "instances.trig", format="trig")

    allowed = {
        KG.availableAt: {
            KG.ScoreSnapshot,
            KG.SECFiling,
            KG.FundamentalMetricSet,
            KG.FundamentalAssessment,
        },
        KG.computedAt: {
            KG.AttractivenessSnapshot,
            KG.FundamentalMetricSet,
            KG.FundamentalAssessment,
        },
        KG.eventTime: {KG.ScoreSnapshot, KG.FundamentalAssessment},
    }
    for predicate, expected in allowed.items():
        for subject, _, _, _ in ds.quads((None, predicate, None, None)):
            types = {obj for _, _, obj, _ in ds.quads((subject, RDF.type, None, None))}
            assert types & expected, (predicate, subject, types)

    g = tbox()
    assert g.value(KG.availableAt, RDFS.domain) is None
    assert g.value(KG.computedAt, RDFS.domain) == KG.Observation
    assert g.value(KG.eventTime, RDFS.domain) == KG.Observation
