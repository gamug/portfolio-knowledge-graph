def test_the_tbox_has_the_35_metric_properties_and_no_price_property() -> None:
    g = tbox()
    actual = {
        subject
        for subject in g.subjects(RDF.type, OWL.DatatypeProperty)
        if (subject, RDFS.domain, KG.FundamentalMetricSet) in g
    }
    assert actual == {KG[name] for name in METRIC_PROPERTIES}
    assert not any((KG[name], RDF.type, OWL.DatatypeProperty) in g for name in EXCLUDED_METRICS)
    for name in EXCLUDED_METRICS:
        assert (KG[name], RDFS.domain, KG.FundamentalMetricSet) not in g


